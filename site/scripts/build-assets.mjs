// Combo editor assets (docs/combo-editor.md): writes site/public/table.glb, a web-sized copy of the committed scene
// assets/scene/full_static_appearance.glb (never edited). Same nodes and materials; the geometry is welded, lightly
// simplified, quantised and meshopt-compressed, and the textures are stored as WebP.
//   node scripts/build-assets.mjs            (run by `npm run dev` and `npm run build`)
import { existsSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { dedup, meshopt, prune, simplify, textureCompress, weld } from "@gltf-transform/functions";
import { MeshoptDecoder, MeshoptEncoder, MeshoptSimplifier } from "meshoptimizer";
import sharp from "sharp";

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(here, "../../assets/scene/full_static_appearance.glb");
const OUT = path.resolve(here, "../public/table.glb");

// The rink numbers the editor needs, cut from the canonical geometry (data/geometry.json) and the hardware report.
{
  const { readFileSync, writeFileSync, mkdirSync } = await import("node:fs");
  const g = JSON.parse(readFileSync(path.resolve(here, "../../data/geometry.json"), "utf8"));
  const hw = JSON.parse(readFileSync(path.resolve(here, "../../validation/12-hardware-report.json"), "utf8"));
  const r2 = (v) => Math.round(v * 100) / 100;
  const rink = {
    note: "generated by site/scripts/build-assets.mjs from data/geometry.json and validation/12-hardware-report.json; do not edit",
    geometry_version: g.geometry_version,
    puck_radius_mm: g.puck.diameter.value / 2,
    slots: Object.fromEntries(g.fixture_paths.map((p) => [p.player_id, p.centreline.points_mm.map((q) => [r2(q[0]), r2(q[1])])])),
    board_mm: g.board.inner_boundary.world.points_mm.map((q) => [r2(q[0]), r2(q[1])]),
    goals: { W: { at_mm: hw.goal.placement_mm.W, mouth_mm: hw.goal.mouth_width_per_goal_mm.W }, E: { at_mm: hw.goal.placement_mm.E, mouth_mm: hw.goal.mouth_width_per_goal_mm.E }, depth_mm: hw.goal.depth_mm },
  };
  mkdirSync(path.resolve(here, "../src/generated"), { recursive: true });
  writeFileSync(path.resolve(here, "../src/generated/rink.json"), JSON.stringify(rink) + "\n");
}

if (existsSync(OUT) && statSync(OUT).mtimeMs > statSync(SRC).mtimeMs && !process.argv.includes("--force")) {
  console.log("table.glb is up to date");
  process.exit(0);
}
await MeshoptDecoder.ready;
await MeshoptEncoder.ready;
await MeshoptSimplifier.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ "meshopt.decoder": MeshoptDecoder, "meshopt.encoder": MeshoptEncoder });
const doc = await io.read(SRC);
const tris = () => doc.getRoot().listMeshes().reduce((n, m) => n + m.listPrimitives().reduce((k, p) => k + (p.getIndices()?.getCount() ?? p.getAttribute("POSITION").getCount()) / 3, 0), 0);
const before = tris();
await doc.transform(
  dedup(),
  weld(),
  // error is a fraction of each mesh's extent: 0.0006 of a 57 mm figure is about 0.03 mm
  simplify({ simplifier: MeshoptSimplifier, ratio: 0.3, error: 0.0006 }),
  prune(),
  textureCompress({ encoder: sharp, targetFormat: "webp", quality: 88 }),
  meshopt({ encoder: MeshoptEncoder, level: "medium" }),
);
await io.write(OUT, doc);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${(statSync(OUT).size / 1e6).toFixed(2)} MB (source ${(statSync(SRC).size / 1e6).toFixed(2)} MB), triangles ${before} -> ${tris()}`);

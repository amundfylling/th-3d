"""Combo editor library (docs/combo-editor.md): the 121 move pictures as editor combos.

    python3 site/scripts/build-library.py        -> site/public/library.json  (committed)

Uses the move-picture builder (scripts/move-pictures/build.py) for the figures, the contacts and the arrows, so the
library shows exactly what `npm run pictures:moves` draws. Like the pictures, these are illustrations (PROPOSED), not
checked traces. Rerun after a change to data/move-pictures/ or to the builder.
"""
import importlib.util
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("mp_build", REPO / "scripts/move-pictures/build.py")
mp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mp)

INDEX = {m["id"]: m for m in json.loads((REPO / "data/encyclopedia/index.json").read_text())["moves"]}
PIDS = [p["player_id"] for p in mp.G["fixture_paths"]]


def thin(line, tol=0.4):
    """Drops points that lie within tol mm of the straight line between their kept neighbours (board runs)."""
    out = [line[0]]
    for i in range(1, len(line) - 1):
        a, b, p = out[-1], line[i + 1], line[i]
        dx, dy = b[0] - a[0], b[1] - a[1]
        n = (dx * dx + dy * dy) ** 0.5
        d = abs(dx * (p[1] - a[1]) - dy * (p[0] - a[0])) / n if n > 1e-9 else 0.0
        if d > tol:
            out.append(p)
    return out + [line[-1]]


def figures(poses, hidden=()):
    """All twelve figures; one the picture leaves out keeps its default place and is marked hidden."""
    out = {pid: {"arc_mm": poses[pid]["arc_mm"], "theta_deg": poses[pid]["theta_deg"]} for pid in PIDS if pid in poses}
    out.update({pid: {**default[pid], "hidden": True} for pid in hidden})
    return {pid: out[pid] for pid in PIDS if pid in out}


default = {pid: {"arc_mm": o["arc_mm"], "theta_deg": o["theta_deg"]} for pid, o in {**mp.default_poses(), **mp.GOALIES}.items()}
moves = []
for path in sorted((REPO / "data/move-pictures").glob("*.json")):
    if path.stem == "formation":
        continue
    sp = json.loads(path.read_text())
    jobs, geo = mp.build(sp)
    meta = INDEX.get(sp.get("index_id", sp["id"]), {})
    moves.append({
        "id": sp["id"], "name": sp.get("name") or meta.get("name") or sp["id"], "level": sp.get("level", meta.get("level")),
        "player": meta.get("player"), "description": sp.get("text") or meta.get("description") or "",
        "source": "puck.no picture" if "puck_no_picture" in sp else "designed from the NTHF text", "view": sp["view"],
        "figures": figures(geo["poses"], geo.get("hidden", ())),
        "puck": {"x_mm": jobs[0]["puckMm"][0], "y_mm": jobs[0]["puckMm"][1]},
        "arrows": [{"points_mm": thin(a)} for a in geo["arrows_mm"]],
        "markers": [{"label": k, "x_mm": p[0], "y_mm": p[1]} for k, p in geo["points_mm"].items() if k.isdigit()],
    })
out = {"note": "generated by site/scripts/build-library.py from data/move-pictures/; illustrations (PROPOSED), not checked traces; do not edit",
       "geometry_version": mp.G["geometry_version"], "default_figures": {pid: default[pid] for pid in PIDS}, "moves": moves}
dst = REPO / "site/public/library.json"
dst.write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")) + "\n")
print("wrote", dst.relative_to(REPO), len(moves), "moves", dst.stat().st_size, "bytes")
